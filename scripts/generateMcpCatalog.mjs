// No dependencies or execution of application code. Generated inventory is not a
// registry: browser-only actions must never become callable through this script.
import { readFile, readdir, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { spawnSync } from 'node:child_process';

const root = fileURLToPath(new URL('../', import.meta.url));
const check = process.argv.includes('--check');
async function files(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  return (await Promise.all(entries.map(e => e.isDirectory() ? files(path.join(dir, e.name)) : [path.join(dir, e.name)]))).flat();
}
const source = await readFile(path.join(root, 'frontend/src/common/scenarios/catalog.ts'), 'utf8');
const backendStatus = { O01: 'migrated-sources-only', O08: 'migrated', O09: 'migrated-core' };
const toolCatalog = JSON.parse(await readFile(path.join(root, 'contracts/mcp/tools.json'), 'utf8'));
const registered = [...toolCatalog.tools, ...toolCatalog.optionalTools].map(t => t.name);
if (new Set(registered).size !== registered.length) throw new Error('Duplicate registered MCP tool');
if (toolCatalog.tools.length !== toolCatalog.defaultToolCount || toolCatalog.optionalTools.length !== toolCatalog.optionalToolCount) throw new Error('Tool count mismatch');
const migrated = {
  'demo.analysis.query': { tools: ['analysis_query'] },
  'office.todo.query': { tools: ['tasks_query'], parameters: { status: 'open' } },
  'office.todo.complete': { tools: ['tasks_query', 'workflow_transition'], composed: true, parameters: { kind: 'travel', action: 'approve' }, note: 'Resolve source ID/version from the task, then perform one transition.' },
  'office.todo.summarize': { tools: ['tasks_query'], composed: true, note: 'Query open/done tasks for the date, paginate and aggregate in the client.' },
  'office.travel.submit': { tools: ['travel_submit'] },
  'office.travel-draft.save': { tools: ['travel_draft_save'] },
  'office.approval.read': { tools: ['records_query'], parameters: { kind: 'approval' } },
  'office.approval.submit': { tools: ['approval_submit'] },
  ...Object.fromEntries(['approve', 'return', 'withdraw'].map(action => ['office.approval.' + action, { tools: ['workflow_transition'], parameters: { kind: 'approval', action } }])),
  'office.expense.read': { tools: ['records_query'], parameters: { kind: 'expense' } },
  'office.expense.check': { tools: ['expense_prepare'], note: 'Omit expenseFormId and use expectedVersion 0.' },
  'office.expense.correct': { tools: ['expense_prepare'], note: 'Supply the returned expenseFormId and its current version.' },
  'office.expense.submit': { tools: ['workflow_transition'], parameters: { kind: 'expense', action: 'submit' } },
  'office.expense.review': { tools: ['workflow_transition'], parameters: { kind: 'expense' }, note: 'Use exactly one action: approve or return, according to the requested decision.' }
};
const scenarios = [...source.matchAll(/\{ id: '([^']+)', title: '([^']+)', group: '([^']+)'(?:, [^}]+)? \}/g)].map(([, id, title, group]) => ({ id, title, group, backendStatus: backendStatus[id] ?? (group === 'protocol' ? 'browser-protocol-only' : 'browser-only') }));
if (scenarios.length !== 31) throw new Error(`Expected 31 scenarios, got ${scenarios.length}`);
const actions = new Map();
for (const file of (await files(path.join(root, 'frontend/src/pc'))).filter(f => f.endsWith('.tsx')).sort()) {
  const text = await readFile(file, 'utf8');
  for (const [, action] of text.matchAll(/action:\s*'([^']+)'/g)) {
    if (action.startsWith('protocol.')) continue;
    const mapping = migrated[action];
    const entry = actions.get(action) ?? { action, tool: mapping?.tools[0] ?? null, tools: mapping?.tools ?? [], status: mapping?.composed ? 'composed-from-primitives' : mapping ? 'implemented' : 'pending-domain-migration', ...(mapping?.parameters ? { parameters: mapping.parameters } : {}), ...(mapping?.note ? { note: mapping.note } : {}), sources: [] };
    entry.sources.push(path.relative(root, file)); actions.set(action, entry);
  }
}
for (const entry of actions.values()) for (const name of entry.tools) if (!registered.includes(name)) throw new Error(`Unregistered tool mapping: ${name}`);
const inventory = { generatedBy: 'scripts/generateMcpCatalog.mjs', note: 'Static Action inventory; shared tools may serve multiple Actions. Composite Actions use repeated primitive calls. Browser-only Actions have no MCP mapping.', scenarios, actions: [...actions.values()].sort((a,b) => a.action.localeCompare(b.action)) };
const go = `// Code generated by scripts/generateMcpCatalog.mjs; DO NOT EDIT.\npackage mcpserver\n\ntype Scenario struct {\n\tID string \x60json:"id"\x60\n\tTitle string \x60json:"title"\x60\n\tGroup string \x60json:"group"\x60\n\tBackendStatus string \x60json:"backendStatus"\x60\n}\nvar scenarioCatalog = []Scenario{\n${scenarios.map(s => `\t{ID: ${JSON.stringify(s.id)}, Title: ${JSON.stringify(s.title)}, Group: ${JSON.stringify(s.group)}, BackendStatus: ${JSON.stringify(s.backendStatus)}},`).join('\n')}\n}\n`;
const formatted=spawnSync('gofmt',[],{input:go,encoding:'utf8'});
if(formatted.status!==0) throw new Error('gofmt failed: '+formatted.stderr);
for (const [relative, content] of [['contracts/mcp/action-mapping.json', JSON.stringify(inventory, null, 2)+'\n'], ['backend/internal/mcpserver/catalog_generated.go', formatted.stdout]]) {
  const target = path.join(root, relative);
  if (check) { if (await readFile(target, 'utf8') !== content) throw new Error(`Stale generated file: ${relative}`); }
  else { await mkdir(path.dirname(target), { recursive: true }); await writeFile(target, content); }
}
console.log(`${scenarios.length} scenarios, ${actions.size} unique business Actions: ${check ? 'verified' : 'generated'}`);
